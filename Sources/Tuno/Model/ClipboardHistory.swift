import AppKit
import Carbon.HIToolbox
import Observation

struct ClipItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let date: Date
    let sourceApp: String?
    /// Gizli: yalnızca kayıtlı bir yüz tanınınca görünür (Yüz Tanıma).
    var hidden = false

    var searchText: String {
        switch content {
        case .text(let text): text
        case .image: "görsel resim image"
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: " ")
        }
    }

    static func == (lhs: ClipItem, rhs: ClipItem) -> Bool { lhs.id == rhs.id }
}

/// Windows'taki Win+V: kopyalanan her şeyi saklar, ⌘⇧V ile menü çubuğu panelinde gösterir.
/// Parola yöneticilerinin "gizli" işaretlediği içerikler kaydedilmez. Metin ve dosya
/// kayıtları yeniden başlatmada korunur; görseller yalnızca bellekte tutulur.
@Observable
@MainActor
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []
    /// Yeni bir şey kopyalanınca kısa özetiyle çağrılır (Dynamic Island).
    @ObservationIgnored var onCopy: ((String) -> Void)?
    var isEnabled: Bool {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey)
            isEnabled ? start() : stop()
        }
    }
    var limit: Int {
        didSet {
            UserDefaults.standard.set(limit, forKey: Self.limitKey)
            trim()
        }
    }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount

    private static let enabledKey = "clipboardHistory"
    private static let limitKey = "clipboardLimit"
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    init() {
        isEnabled = UserDefaults.standard.bool(forKey: Self.enabledKey, default: true)
        let storedLimit = UserDefaults.standard.integer(forKey: Self.limitKey)
        limit = storedLimit > 0 ? storedLimit : 50
        load()
        if isEnabled { start() }
        NotificationCenter.default.addObserver(forName: .tunoFaceIDRemoved, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.unhideAll() }
        }
    }

    var hasHidden: Bool { items.contains { $0.hidden } }

    func setHidden(_ item: ClipItem, _ hidden: Bool) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].hidden = hidden
        save()
    }

    func unhideAll() {
        guard hasHidden else { return }
        for index in items.indices { items[index].hidden = false }
        save()
    }

    private func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let content: ClipItem.Content?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
            as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(text)
        } else if let image = NSImage(pasteboard: pasteboard) {
            content = .image(image)
        } else {
            content = nil
        }
        guard let content else { return }
        add(ClipItem(content: content, date: Date(),
                     sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName))
        switch content {
        case .text(let text): onCopy?(text.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines)[0])
        case .image: onCopy?(L("Görsel"))
        case .files(let urls): onCopy?(urls.count == 1 ? urls[0].lastPathComponent : String(format: L("%d dosya"), urls.count))
        }
    }

    private func add(_ item: ClipItem) {
        // Aynı metin/dosya tekrar kopyalandıysa en üste taşı (gizliyse gizli kalır).
        var item = item
        items.removeAll { existing in
            let same = switch (existing.content, item.content) {
            case (.text(let a), .text(let b)): a == b
            case (.files(let a), .files(let b)): a == b
            default: false
            }
            if same, existing.hidden { item.hidden = true }
            return same
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        if items.count > limit { items.removeLast(items.count - limit) }
        // Bellek için en fazla 15 görsel tut.
        var images = 0
        items.removeAll { item in
            guard case .image = item.content else { return false }
            images += 1
            return images > 15
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    /// Öğeyi panoya yazar ve öndeki uygulamaya ⌘V gönderir.
    func paste(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount
        add(ClipItem(content: item.content, date: Date(), sourceApp: item.sourceApp, hidden: item.hidden))

        // Panel kapanıp odak önceki uygulamaya dönsün diye kısa bekle.
        let vKey = KeyboardLayout.keyCode(for: "v", fallback: kVK_ANSI_V)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            SyntheticEvent.postKey(vKey, flags: .maskCommand)
        }
    }

    // MARK: - Kalıcılık (metin ve dosyalar)

    private struct Stored: Codable {
        var text: String?
        var files: [URL]?
        var date: Date
        var sourceApp: String?
        /// Gizli öğenin şifreli içeriği (metin ya da dosya yolları).
        var secret: Data?
        var hidden: Bool?
    }

    private static var storeURL: URL {
        let directory = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Tuno", isDirectory: true)
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        return directory.appendingPathComponent("clipboard.json")
    }

    private func save() {
        let stored = items.compactMap { item -> Stored? in
            if item.hidden {
                // Gizli öğe diskte şifreli durur; şifrelenemezse kaydedilmez.
                let plain: Data? = switch item.content {
                case .text(let text): Data(("t:" + text).utf8)
                case .files(let urls): Data(("f:" + urls.map(\.path).joined(separator: "\n")).utf8)
                case .image: nil
                }
                guard let plain, let secret = FaceSecret.seal(plain) else { return nil }
                return Stored(date: item.date, sourceApp: item.sourceApp, secret: secret, hidden: true)
            }
            switch item.content {
            case .text(let text): return Stored(text: text, date: item.date, sourceApp: item.sourceApp)
            case .files(let urls): return Stored(files: urls, date: item.date, sourceApp: item.sourceApp)
            case .image: return nil
            }
        }
        if let data = try? JSONEncoder().encode(stored) {
            var url = Self.storeURL
            try? data.write(to: url, options: .atomic)
            // Kopyalanan metinler hassas olabilir: yalnızca bu kullanıcı okuyabilir ve Time Machine yedeğine girmez.
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try? url.setResourceValues(values)
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: Self.storeURL),
              let stored = try? JSONDecoder().decode([Stored].self, from: data) else { return }
        items = stored.compactMap { entry in
            if let secret = entry.secret {
                guard let data = FaceSecret.open(secret), let plain = String(data: data, encoding: .utf8) else { return nil }
                let body = String(plain.dropFirst(2))
                let content: ClipItem.Content = plain.hasPrefix("f:")
                    ? .files(body.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }) : .text(body)
                return ClipItem(content: content, date: entry.date, sourceApp: entry.sourceApp, hidden: true)
            }
            if let text = entry.text { return ClipItem(content: .text(text), date: entry.date, sourceApp: entry.sourceApp) }
            if let files = entry.files { return ClipItem(content: .files(files), date: entry.date, sourceApp: entry.sourceApp) }
            return nil
        }
    }
}
