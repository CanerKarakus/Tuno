/// Metin çevirisi. Anahtar olarak Türkçe metnin kendisi kullanılır: `Text(L("Dil seçin"))`.
/// Tablo yoksa Türkçe metin gösterilir, bu yüzden çeviri eksik kalsa da uygulama bozulmaz.
func L(_ turkish: String) -> String {
    switch AppLanguage.current {
    case .tr: turkish
    case .en: english[turkish] ?? turkish
    case .es: spanish[turkish] ?? turkish
    }
}

/// Aynı Türkçe metin farklı yerlerde farklı anlama geliyorsa (ör. "İleri": sonraki düğmesi / fare ileri tuşu)
/// bağlamla çevrilir: tablo anahtarı "bağlam|Türkçe". Bağlam tabloda yoksa normal L() kullanılır.
func Lc(_ turkish: String, _ context: String) -> String {
    switch AppLanguage.current {
    case .tr: turkish
    case .en: english["\(context)|\(turkish)"] ?? L(turkish)
    case .es: spanish["\(context)|\(turkish)"] ?? L(turkish)
    }
}

